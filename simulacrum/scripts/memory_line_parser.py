    def parse_memory_content(self) -> List[Dict[str, Any]]:
        """解析記憶內容，一行一行處理，根據段落標明分類"""
        memories = []
        current_section = None

        for line_num, line in enumerate(self.memory_content.split('\n'), 1):
            line = line.strip()
            if not line:
                continue

            # 檢查是否為段落標題
            if line == '情節記憶':
                current_section = 'episodic'
                continue  # 跳過標題行，不作為記憶內容
            elif line == '語意記憶':
                current_section = 'semantic'
                continue  # 跳過標題行，不作為記憶內容
            elif line == '情緒記憶':
                current_section = 'emotional'
                continue  # 跳過標題行，不作為記憶內容
            else:
                # 普通內容行，使用當前段落類型
                content = line
                if current_section is None:
                    current_section = 'general'  # 預設類型

            # 創建記憶物件
            memory = {
                'type': current_section,
                'content': content,
                'line_number': line_num
            }
            memories.append(memory)

        return memories

